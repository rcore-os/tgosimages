#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../../.." && pwd -P)
SOURCE_DIR="${SOURCE_DIR:-${ROOT_DIR}/IMAGES/orangepi/ivc}"
LINUX_DIR="${LINUX_DIR:-${ROOT_DIR}/IMAGES/orangepi/linux}"
STARRY_DIR="${STARRY_DIR:-${ROOT_DIR}/IMAGES/orangepi/starry}"
ZEPHYR_DIR="${ZEPHYR_DIR:-${ROOT_DIR}/IMAGES/orangepi/zephyr}"
STAGE_DIR="${STAGE_DIR:-${ROOT_DIR}/build/orangepi/ivc-test}"
LINUX_ROOTFS="${LINUX_ROOTFS:-${ROOT_DIR}/IMAGES/rootfs/rootfs-aarch64-busybox.img}"
STARRY_ROOTFS="${STARRY_ROOTFS:-${ROOT_DIR}/IMAGES/rootfs/rootfs-aarch64-orangepi-jammy.img}"
AXVISOR_DIR="${AXVISOR_DIR:-}"

usage() {
    cat <<'EOF'
Stage the Orange Pi IVC board filesystem.

Usage: scripts/tests/apps/orangepi-ivc-test-fs.sh [--stage-dir PATH]

The output is copied to the board separately; this script never writes
/guest/ivc-test on the build host.

Set SOURCE_DIR, LINUX_DIR, STARRY_DIR and ZEPHYR_DIR to the build outputs.
LINUX_ROOTFS and STARRY_ROOTFS default to the existing guest images in IMAGES/rootfs.
The staged rootfs/ paths keep the original guest filesystem filenames.
Set AXVISOR_DIR to include the single ivc.bin and ivc.fit host image.
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --stage-dir) STAGE_DIR="$2"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

if [[ "${STAGE_DIR}" == "/guest/ivc-test" ]]; then
    echo "refusing to stage into host /guest/ivc-test; use a local staging directory" >&2
    exit 1
fi

declare -A artifacts=(
    [linux/orangepi-5-plus]="${LINUX_DIR}/orangepi-5-plus"
    [starry/orangepi-5-plus]="${STARRY_DIR}/orangepi-5-plus"
    [zephyr/orangepi-5-plus]="${ZEPHYR_DIR}/orangepi-5-plus"
    [zephyr/orangepi-5-plus.dtb]="${ZEPHYR_DIR}/orangepi-5-plus.dtb"
    [usr/bin/ivc-roundtrip]="${SOURCE_DIR}/usr/bin/ivc-roundtrip"
    [usr/bin/ivc-demo]="${SOURCE_DIR}/usr/bin/ivc-demo"
    [usr/bin/ivc-starry-bench]="${SOURCE_DIR}/usr/bin/ivc-starry-bench"
)

# The Linux initramfs is produced alongside the prepared AXIVC assets.
artifacts[linux/initramfs.cpio]="${LINUX_DIR}/initramfs.cpio"
artifacts[linux/axvisor.ko]="${LINUX_DIR}/lib/modules/axvisor.ko"
for program in axivc-pub axivc-sub axivc-pingpong; do
    artifacts[usr/bin/${program}]="${LINUX_DIR}/usr/bin/${program}"
done
artifacts[rootfs/rootfs-aarch64-busybox.img]="${LINUX_ROOTFS}"
artifacts[rootfs/rootfs-aarch64-orangepi-jammy.img]="${STARRY_ROOTFS}"

if [[ -n "${AXVISOR_DIR}" ]]; then
    for case in ivc; do
        for extension in bin fit; do
            artifacts[axvisor/${case}.${extension}]="${AXVISOR_DIR}/${case}.${extension}"
        done
    done
fi

rm -rf "${STAGE_DIR}"
mkdir -p "${STAGE_DIR}"
manifest="${STAGE_DIR}/manifest.toml"
{
    echo '# Generated by orangepi-ivc-test-fs.sh'
    echo 'version = 1'
    echo
} >"${manifest}"

for relative in "${!artifacts[@]}"; do
    source=${artifacts[${relative}]}
    [[ -s "${source}" ]] || { echo "missing required artifact: ${source}" >&2; exit 1; }
    destination="${STAGE_DIR}/${relative}"
    mkdir -p "$(dirname -- "${destination}")"
    install -m 0644 "${source}" "${destination}"
    case "${relative}" in usr/bin/*) chmod 0755 "${destination}" ;; esac
    checksum=$(sha256sum "${destination}" | awk '{print $1}')
    size=$(stat -c '%s' "${destination}")
    mode=$(stat -c '%a' "${destination}")
    # Paths, modes and digests are emitted as TOML basic strings.  Shell
    # printf %q is not TOML quoting and produces an invalid manifest for
    # values such as /guest/ivc-test/zephyr/orangepi-5-plus.
    printf '[[artifact]]\npath = "%s"\nsize = %s\nmode = "%s"\nsha256 = "%s"\n\n' \
        "/guest/ivc-test/${relative}" "${size}" "${mode}" "${checksum}" >>"${manifest}"
done

python3 - "${manifest}" <<'PY'
import pathlib
import sys
import tomllib

manifest = pathlib.Path(sys.argv[1])
with manifest.open("rb") as stream:
    data = tomllib.load(stream)
artifacts = data.get("artifact", [])
if data.get("version") != 1 or len(artifacts) == 0:
    raise SystemExit("invalid IVC test manifest metadata")
for artifact in artifacts:
    for key in ("path", "size", "mode", "sha256"):
        if key not in artifact:
            raise SystemExit(f"manifest artifact is missing {key}: {artifact!r}")
PY

echo "staged Orange Pi IVC filesystem: ${STAGE_DIR}"
echo "copy this directory to the board as /guest/ivc-test"
