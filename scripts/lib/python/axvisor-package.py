#!/usr/bin/env python3
"""Install existing BallPick configurations without duplicating shared guests."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tomllib

BOARD = Path('apps/axvisor/normal/board-ballpick-robot')
DESTINATION = '/guest/axvisor/board-ballpick-robot'


def package(source, output, build_config):
    source = source.resolve()
    board = source / BOARD
    if not board.is_dir() or board.is_symlink():
        raise ValueError(f'BallPick configuration directory missing or symlink: {board}')
    documents = {}
    files = []
    for path in sorted(board.rglob('*')):
        if path.is_symlink():
            raise ValueError(f'configuration tree contains a symlink: {path}')
        if not path.is_file() or path.suffix not in ('.toml', '.md'):
            continue
        files.append(path)
        if path.suffix == '.toml':
            documents[path.relative_to(board).as_posix()] = tomllib.loads(path.read_text())
    if not documents:
        raise ValueError(f'no BallPick configurations found: {board}')
    runtime, dependent, scenarios, dependent_scenarios = [], [], {}, {}
    for relative, document in documents.items():
        if 'base' in document and 'kernel' in document:
            kernel = document['kernel']
            paths = [kernel[field] for field in ('kernel_path', 'dtb_path', 'ramdisk_path')
                     if field in kernel]
            paths.extend(device['path'] for device in document.get('devices', {}).get('virtual', [])
                         if 'path' in device)
            installed = f'{DESTINATION}/{relative}'
            (runtime if paths and all(isinstance(p, str) and p.startswith('/guest/')
                                      for p in paths) else dependent).append(installed)
        if 'vm_configs' in document:
            references = document['vm_configs']
            if not isinstance(references, list) or not all(isinstance(p, str) for p in references):
                raise ValueError(f'invalid vm_configs in {relative}')
            installed = []
            for reference in references:
                if Path(reference).parts[:1] == ('target',) and '..' not in Path(reference).parts:
                    # These are generated by the scale-test runner, not stored
                    # guest definitions. Never bake in a local target tree.
                    dependent_scenarios.setdefault(relative, []).append(reference)
                    continue
                referenced = source / reference
                if not referenced.resolve().is_relative_to(board.resolve()):
                    raise ValueError(f'vm_configs reference escapes BallPick tree: {reference}')
                if not referenced.is_file():
                    raise ValueError(f'missing vm_configs reference: {reference}')
                guest = referenced.relative_to(board).as_posix()
                if guest not in documents or not {'base', 'kernel'} <= documents[guest].keys():
                    raise ValueError(f'vm_configs reference is not a guest configuration: {reference}')
                installed.append(f'{DESTINATION}/{guest}')
            scenarios[relative] = installed
    # Validate before copying anything; the shell builder publishes this tree
    # together with the matching host image only after every step succeeds.
    host = tomllib.loads(build_config.read_text())
    if host.get('vm_configs'):
        raise ValueError('shared AxVisor build config must use vm_configs = []; load guests from disk')
    if not host.get('target', '').startswith('aarch64-'):
        raise ValueError('Orange Pi AxVisor build config must select an aarch64 target')
    output.mkdir(parents=True, exist_ok=True)
    for path in files:
        target = output / 'board-ballpick-robot' / path.relative_to(board)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    shutil.copyfile(build_config, output / 'build.toml')
    commit = subprocess.check_output(['git', '-C', source, 'rev-parse', 'HEAD'], text=True).strip()
    dirty = bool(subprocess.check_output(['git', '-C', source, 'status', '--porcelain'], text=True))
    manifest = dict(schema_version=1, platform='orangepi-5-plus', image='AxVisor.bin',
                    image_partition='linux-boot', boot_partition_path='/AxVisor.bin',
                    source_commit=commit, source_dirty=dirty,
                    build_config=str(build_config.relative_to(source)),
                    runtime_guest_configs=runtime, source_dependent_guest_configs=dependent,
                    scenarios=scenarios, source_dependent_scenarios=dependent_scenarios)
    lock = source / 'Cargo.lock'
    if lock.is_file():
        manifest['source_lock_sha256'] = hashlib.sha256(lock.read_bytes()).hexdigest()
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--build-config', required=True, type=Path)
    args = parser.parse_args()
    package(args.source, args.output, args.build_config)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f'AxVisor package: {error}', file=sys.stderr)
        sys.exit(1)
