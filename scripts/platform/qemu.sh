linux() {
    local linux_images_dir="${PLATFORM_IMAGES_DIR}/linux"
    local image_targets=()
    local image_sources=()
    local image_outputs=()

    info "Cloning ${ARCH} Linux source repository $LINUX_REPO_URL"
    clone_repository "$LINUX_REPO_URL" "$LINUX_SRC_DIR"
    info "Checking out ${ARCH} Linux ref ${LINUX_REF}"
    checkout_ref "$LINUX_SRC_DIR" "$LINUX_REF"

    info "Applying patches..."
    apply_patches "$LINUX_PATCH_DIR" "$LINUX_SRC_DIR"

    info "Starting to build ${ARCH} Linux OS..."
    local commands=("$@")
    case "${ARCH}" in
        aarch64)
            local linux_arch="arm64"
            local cross_compile="${AARCH64_CROSS_COMPILE:-aarch64-linux-gnu-}"
            local defconfig="defconfig"
            image_sources=("arch/arm64/boot/Image")
            image_outputs=("linux-qemu")
            ;;
        riscv64)
            local linux_arch="riscv"
            local cross_compile="${RISCV64_CROSS_COMPILE:-riscv64-linux-gnu-}"
            local defconfig="defconfig"
            image_sources=("arch/riscv/boot/Image")
            image_outputs=("linux-qemu")
            ;;
        x86_64)
            local linux_arch="x86"
            local cross_compile="${X86_CROSS_COMPILE:-}"
            local defconfig="x86_64_defconfig"
            image_sources=("arch/x86/boot/bzImage")
            image_outputs=("linux-qemu")
            ;;
        loongarch64)
            local linux_arch="loongarch"
            local cross_compile="${LOONGARCH64_CROSS_COMPILE:-loongarch64-linux-gnu-}"
            local defconfig="loongson64_defconfig"
            image_targets=("vmlinuz.efi" "vmlinux.elf")
            image_sources=("arch/loongarch/boot/vmlinuz.efi" "arch/loongarch/boot/vmlinux.elf")
            image_outputs=("vmlinuz.efi" "vmlinux.elf")
            ;;
        *)
            die "Unsupported Linux architecture: ${ARCH}"
            ;;
    esac
    
    pushd "${LINUX_SRC_DIR}" >/dev/null

    # info "Cleaning Linux: make distclean"
    # make distclean || true

    if [[ "$@" != *"clean"* ]]; then
        if [[ ${#commands[@]} -eq 0 ]] || [[ "${commands[0]}" == "all" ]]; then
            info "Configuring Linux: make ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} ${defconfig}"
            make ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "${defconfig}" || {
                local status=$?
                popd >/dev/null
                return "$status"
            }
        fi
        
        if [[ (${#commands[@]} -eq 0 || "${commands[0]}" == "all") && ${#image_targets[@]} -gt 0 ]]; then
            info "Building Linux image targets: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} ${image_targets[*]}"
            make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "${image_targets[@]}" || {
                local status=$?
                popd >/dev/null
                return "$status"
            }
        elif [[ ${#commands[@]} -eq 0 ]]; then
            info "Building Linux: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile}"
            make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" || {
                local status=$?
                popd >/dev/null
                return "$status"
            }
        else
            info "Building Linux: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} ${commands[*]}"
            make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "${commands[@]}" || {
                local status=$?
                popd >/dev/null
                return "$status"
            }
        fi
        
        popd >/dev/null

        # If it's a full build, copy the image and create the root filesystem
        if [[ ${#commands[@]} -eq 0 ]] || [[ "${commands[0]}" == "all" ]]; then
            mkdir -p "${linux_images_dir}"
            rm -f "${linux_images_dir}/linux-qemu"
            if [[ "${ARCH}" == "loongarch64" ]]; then
                rm -f "${linux_images_dir}/vmlinuz.efi" \
                      "${linux_images_dir}/vmlinux.elf" \
                      "${linux_images_dir}/qemu-loongarch64"
            fi
            local i
            for i in "${!image_sources[@]}"; do
                KIMG_PATH="${LINUX_SRC_DIR}/${image_sources[$i]}"
                [[ -f "${KIMG_PATH}" ]] || die "Kernel image not found: ${KIMG_PATH}"
                info "Copying image: ${KIMG_PATH} -> ${linux_images_dir}/${image_outputs[$i]}"
                cp -f "${KIMG_PATH}" "${linux_images_dir}/${image_outputs[$i]}"
            done
            if [[ "${ARCH}" == "loongarch64" ]]; then
                cp -f "${linux_images_dir}/vmlinux.elf" "${linux_images_dir}/linux-qemu"
            fi
            
        fi
    else
        info "Building Linux: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} clean"
        make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "clean"
        info "Removing ${linux_images_dir}/*"
        rm -rf "${linux_images_dir}"/* || true
    fi
}

arceos() {
    case "${ARCH}" in
        aarch64)
            local platform="aarch64-dyn"
            ;;
        riscv64)
            local platform="riscv64-qemu-virt"
            ;;
        x86_64)
            local platform="x86-pc"
            ;;
        *)
            die "Unsupported ArceOS architecture: ${ARCH}"
            ;;
    esac
    
    local arceos_images_dir="${PLATFORM_IMAGES_DIR}/arceos"
    info "Building ArceOS using tgoskits for platform: $platform -> $arceos_images_dir"

    bash "${SCRIPT_DIR}/../os/arceos.sh" "$platform" --images-dir "${arceos_images_dir}" --image-name "arceos-qemu" "$@"
}

qemu_ivc_arceos_config() {
    local package="$1"
    local config_dir="${BUILD_DIR}/qemu-${ARCH}-ivc"
    local config_path="${config_dir}/${package}.toml"

    mkdir -p "${config_dir}"
    cat > "${config_path}" <<'EOF'
features = ["arceos"]
log = "Warn"
EOF
    printf '%s\n' "${config_path}"
}

qemu_ivc_require_file() {
    local path="$1"
    local description="$2"

    [[ -f "${path}" ]] || die "Missing ${description}: ${path}"
}

qemu_ivc_build_arceos_guest() {
    local package="$1"
    local image_name="$2"
    local arceos_images_dir="${PLATFORM_IMAGES_DIR}/arceos"
    local image_path="${arceos_images_dir}/${image_name}"
    local config_path

    [[ "${ARCH}" == "aarch64" ]] || die "Axvisor IVC payload is currently only supported for qemu aarch64"
    if [[ -f "${image_path}" ]]; then
        info "Using existing Axvisor IVC ArceOS guest image: ${image_path}"
        return 0
    fi

    info "Building Axvisor IVC ArceOS guest: ${package} -> ${image_path}"
    config_path="$(qemu_ivc_arceos_config "${package}")"
    bash "${SCRIPT_DIR}/../os/arceos.sh" \
        aarch64-dyn \
        --images-dir "${arceos_images_dir}" \
        --image-name "${image_name}" \
        --package "${package}" \
        --target aarch64-unknown-none-softfloat \
        --config "${config_path}"

    qemu_ivc_require_file "${image_path}" "Axvisor IVC ArceOS guest image (${package})"
}

qemu_ivc_ensure_linux_guest() {
    local linux_image="${PLATFORM_IMAGES_DIR}/linux/linux-qemu"

    [[ "${ARCH}" == "aarch64" ]] || die "Axvisor IVC Linux guest is currently only supported for qemu aarch64"
    if [[ -f "${linux_image}" ]]; then
        info "Using existing qemu aarch64 Linux guest image: ${linux_image}"
        return 0
    fi

    linux
}

qemu_ivc_build_linux_tools() {
    local ivc_dir="${AXVISOR_TOOLS_SRC_DIR}/ivc"
    local overlay_dir="$1"
    local module="${ivc_dir}/kernel_driver/axvisor.ko"
    local subscriber="${ivc_dir}/subscribe-aarch64"
    local built_subscriber="${ivc_dir}/build/demo/subscribe"

    if [[ "${AXVISOR_TOOLS_SKIP_CHECKOUT}" == "1" ]]; then
        [[ -d "${AXVISOR_TOOLS_SRC_DIR}" ]] || die "AXVISOR_TOOLS_SRC_DIR does not exist: ${AXVISOR_TOOLS_SRC_DIR}"
        info "Using existing axvisor-tools source tree without checkout: ${AXVISOR_TOOLS_SRC_DIR}"
    else
        clone_repository "${AXVISOR_TOOLS_REPO_URL}" "${AXVISOR_TOOLS_SRC_DIR}"
        checkout_ref "${AXVISOR_TOOLS_SRC_DIR}" "${AXVISOR_TOOLS_REF}"
    fi

    if [[ ! -f "${subscriber}" ]]; then
        info "Building Axvisor IVC Linux subscriber demo"
        make -C "${ivc_dir}" \
            ARCH=arm64 \
            CROSS="${AARCH64_MUSL_CROSS:-aarch64-linux-musl-}" \
            demo
        [[ -f "${built_subscriber}" ]] || die "Linux IVC subscriber demo was not produced: ${built_subscriber}"
        cp -f "${built_subscriber}" "${subscriber}"
        chmod +x "${subscriber}"
    else
        info "Using existing Axvisor IVC Linux subscriber demo: ${subscriber}"
    fi

    info "Building Axvisor IVC Linux kernel module"
    make -C "${ivc_dir}/kernel_driver" \
        ARCH=arm64 \
        CROSS_COMPILE="${AARCH64_CROSS_COMPILE:-aarch64-linux-gnu-}" \
        KDIR="${LINUX_SRC_DIR}" \
        clean
    make -C "${ivc_dir}/kernel_driver" \
        ARCH=arm64 \
        CROSS_COMPILE="${AARCH64_CROSS_COMPILE:-aarch64-linux-gnu-}" \
        KDIR="${LINUX_SRC_DIR}"
    [[ -f "${module}" ]] || die "Linux IVC kernel module was not produced: ${module}"
    qemu_ivc_require_file "${subscriber}" "Linux IVC subscriber demo"

    mkdir -p "${overlay_dir}/root"
    cp -f "${module}" "${overlay_dir}/root/axvisor.ko"
    cp -f "${subscriber}" "${overlay_dir}/root/ivc-subscribe"
    chmod 0755 "${overlay_dir}/root/ivc-subscribe"

    qemu_ivc_require_file "${overlay_dir}/root/axvisor.ko" "rootfs overlay axvisor kernel module"
    qemu_ivc_require_file "${overlay_dir}/root/ivc-subscribe" "rootfs overlay Linux IVC subscriber demo"
}

qemu_ivc_validate_payloads() {
    local overlay_dir="$1"

    qemu_ivc_require_file "${PLATFORM_IMAGES_DIR}/arceos/arceos-ivc-publisher.bin" "Axvisor IVC ArceOS publisher image"
    qemu_ivc_require_file "${PLATFORM_IMAGES_DIR}/arceos/arceos-ivc-subscriber.bin" "Axvisor IVC ArceOS subscriber image"
    qemu_ivc_require_file "${overlay_dir}/root/axvisor.ko" "Axvisor IVC Linux kernel module overlay"
    qemu_ivc_require_file "${overlay_dir}/root/ivc-subscribe" "Axvisor IVC Linux subscriber overlay"
    success "Axvisor IVC rootfs payloads are ready"
}

qemu_ivc_validate_staged_payloads() {
    local stage_dir="$1"
    local overlay_dir="$2"

    qemu_ivc_require_file "${stage_dir}/guest/arceos/arceos-ivc-publisher.bin" "staged Axvisor IVC ArceOS publisher image"
    qemu_ivc_require_file "${stage_dir}/guest/arceos/arceos-ivc-subscriber.bin" "staged Axvisor IVC ArceOS subscriber image"
    qemu_ivc_require_file "${overlay_dir}/root/axvisor.ko" "staged Axvisor IVC Linux kernel module overlay"
    qemu_ivc_require_file "${overlay_dir}/root/ivc-subscribe" "staged Axvisor IVC Linux subscriber overlay"
}

qemu_prepare_ivc_payloads() {
    local overlay_dir="${BUILD_DIR}/qemu-${ARCH}-ivc-rootfs-overlay"

    [[ "${ARCH}" == "aarch64" ]] || return 0

    qemu_ivc_ensure_linux_guest

    rm -rf "${overlay_dir}"
    qemu_ivc_build_arceos_guest "arceos-ivc-publisher" "arceos-ivc-publisher.bin"
    qemu_ivc_build_arceos_guest "arceos-ivc-subscriber" "arceos-ivc-subscriber.bin"
    qemu_ivc_build_linux_tools "${overlay_dir}"
    qemu_ivc_validate_payloads "${overlay_dir}"
}

