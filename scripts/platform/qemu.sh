qemu_rootfs_clean_outputs() {
    local rootfs_builder

    [[ ${#ROOTFS_BUILDERS[@]} -gt 0 ]] || return 0

    for rootfs_builder in "${ROOTFS_BUILDERS[@]}"; do
        case "${rootfs_builder}" in
            busybox)
                rm -f "${ROOT_DIR}/IMAGES/rootfs/initramfs-${ARCH}-busybox.cpio.gz"
                rm -f "${ROOT_DIR}/IMAGES/rootfs/rootfs-${ARCH}-busybox.img"
                ;;
            alpine)
                rm -f "${ROOT_DIR}/IMAGES/rootfs/rootfs-${ARCH}-alpine.img"
                ;;
            debian)
                rm -f "${ROOT_DIR}/IMAGES/rootfs/rootfs-${ARCH}-debian.img"
                ;;
            *)
                die "Unsupported rootfs builder: ${rootfs_builder} (supported: busybox, alpine, debian)"
                ;;
        esac
    done
}

qemu_rootfs_parse_args() {
    BUILD_ARGS=()
    ROOTFS_BUILD_ARGS=()
    ROOTFS_BUILDERS=()
    QEMU_OUTER_FREE_SIZE=""

    local builder
    local seen
    local -A rootfs_seen=()

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --rootfs)
                [[ $# -ge 2 ]] || die "--rootfs requires a value"
                IFS=',' read -r -a seen <<< "$2"
                for builder in "${seen[@]}"; do
                    [[ -n "${builder}" ]] || continue
                    case "${builder}" in
                        busybox|alpine|debian)
                            [[ -n "${rootfs_seen[${builder}]:-}" ]] && continue
                            rootfs_seen["${builder}"]=1
                            ROOTFS_BUILDERS+=("${builder}")
                            ;;
                        *)
                            die "Unsupported rootfs builder: ${builder} (supported: busybox, alpine, debian)"
                            ;;
                    esac
                done
                shift 2
                ;;
            --outer-tests|--guest-tests|--guest-free-size|--outer-free-size)
                [[ $# -ge 2 ]] || die "$1 requires a value"
                [[ "$2" != --* ]] || die "$1 requires a value"
                ROOTFS_BUILD_ARGS+=("$1" "$2")
                if [[ "$1" == "--outer-free-size" ]]; then
                    QEMU_OUTER_FREE_SIZE="$2"
                fi
                shift 2
                ;;
            *)
                BUILD_ARGS+=("$1")
                shift
                ;;
        esac
    done

    if [[ ${#ROOTFS_BUILDERS[@]} -gt 0 ]]; then
        return 0
    fi

    case "${OS}" in
        clean|help|-h|--help|"")
            return 0
            ;;
    esac

    if [[ "${ARCH}" == "loongarch64" ]]; then
        ROOTFS_BUILDERS=(busybox alpine)
    else
        ROOTFS_BUILDERS=(busybox alpine debian)
    fi
}

qemu_rootfs_build_step() {
    local rootfs_builder="$1"

    bash "${SCRIPT_DIR}/../rootfs/${rootfs_builder}.sh" \
        "${ARCH}" --out_dir "${ROOT_DIR}/IMAGES/rootfs" "${ROOTFS_BUILD_ARGS[@]}"
}

qemu_rootfs_busybox_step() { qemu_rootfs_build_step busybox; }
qemu_rootfs_alpine_step() { qemu_rootfs_build_step alpine; }
qemu_rootfs_debian_step() { qemu_rootfs_build_step debian; }

qemu_has_help_arg() {
    local arg

    for arg in "$@"; do
        case "${arg}" in
            help|-h|--help)
                return 0
                ;;
        esac
    done
    return 1
}

qemu_rootfs_inject_platform_dir() (
    local guest_dir="${PLATFORM_IMAGES_DIR}"
    local stage_dir
    local ivc_overlay_dir="${BUILD_DIR}/qemu-${ARCH}-ivc-rootfs-overlay"
    local rootfs_builder
    local has_aarch64_alpine=0
    local empty_overlay_dir
    local alpine_stage_dir=""
    local builder_guest_dir
    local protected_basename
    local outer_image
    local outer_reserve="${QEMU_OUTER_FREE_SIZE:-256M}"

    [[ ${#ROOTFS_BUILDERS[@]} -gt 0 ]] || return 0

    for rootfs_builder in "${ROOTFS_BUILDERS[@]}"; do
        if [[ "${ARCH}" == "aarch64" && "${rootfs_builder}" == "alpine" ]]; then
            has_aarch64_alpine=1
            break
        fi
    done

    if [[ ! -d "${guest_dir}" && "${has_aarch64_alpine}" -ne 1 ]]; then
        warn "No guest payload was produced for qemu ${ARCH}, skipping rootfs injection"
        return 0
    fi

    stage_dir="$(mktemp -d "${BUILD_DIR}/qemu-rootfs-${ARCH}.XXXXXX")"
    trap 'rm -rf "${stage_dir}"; [[ -z "${alpine_stage_dir:-}" ]] || rm -rf "${alpine_stage_dir}"' EXIT
    empty_overlay_dir="${stage_dir}/empty-overlay"
    mkdir -p "${empty_overlay_dir}"
    if [[ -d "${guest_dir}" ]]; then
        rootfs_stage_guest_tree "${stage_dir}" "${guest_dir}"
    else
        mkdir -p "${stage_dir}/guest"
    fi
    # QEMU owns this staging copy. Build outputs commonly carry nanosecond
    # timestamps, while the verified debugfs injector intentionally accepts
    # only whole-second metadata. Normalize the private copy, not IMAGES/.
    _rootfs_builder_normalize_overlay_seconds "${stage_dir}" || return 1

    if [[ "${has_aarch64_alpine}" -eq 1 ]]; then
        qemu_prepare_ivc_payloads
        alpine_stage_dir="$(mktemp -d "${BUILD_DIR}/qemu-rootfs-${ARCH}-alpine.XXXXXX")"
        rootfs_stage_guest_tree "${alpine_stage_dir}" "${guest_dir}"
        qemu_ivc_validate_staged_payloads "${alpine_stage_dir}" "${ivc_overlay_dir}"
        _rootfs_builder_normalize_overlay_seconds "${alpine_stage_dir}" || return 1
        _rootfs_builder_normalize_overlay_seconds "${ivc_overlay_dir}" || return 1
    fi

    # Reject every protected nested-image basename before touching any output.
    for rootfs_builder in "${ROOTFS_BUILDERS[@]}"; do
        protected_basename="rootfs-${ARCH}-${rootfs_builder}.img"
        if [[ -e "${stage_dir}/guest/${protected_basename}" || -L "${stage_dir}/guest/${protected_basename}" ]]; then
            die "Platform payload collides with protected nested image basename: ${protected_basename}"
        fi
        if [[ -n "${alpine_stage_dir}" && ( -e "${alpine_stage_dir}/guest/${protected_basename}" || -L "${alpine_stage_dir}/guest/${protected_basename}" ) ]]; then
            die "Platform payload collides with protected nested image basename: ${protected_basename}"
        fi
    done

    for rootfs_builder in "${ROOTFS_BUILDERS[@]}"; do
        protected_basename="rootfs-${ARCH}-${rootfs_builder}.img"
        outer_image="${ROOT_DIR}/IMAGES/rootfs/${protected_basename}"
        builder_guest_dir="${stage_dir}/guest"
        if [[ "${ARCH}" == "aarch64" && "${rootfs_builder}" == "alpine" ]]; then
            builder_guest_dir="${alpine_stage_dir}/guest"
        fi
        case "${rootfs_builder}" in
            busybox)
                _rootfs_builder_normalize_overlay_seconds "${builder_guest_dir}" || return 1
                rootfs_inject_guest_stage "${ROOT_DIR}/IMAGES/rootfs/initramfs-${ARCH}-busybox.cpio.gz" "${builder_guest_dir}" || return 1
                # Reading the staging tree while repacking cpio can advance
                # atime with nanosecond precision. Normalize this private copy
                # again before the strict ext4 payload validation.
                _rootfs_builder_normalize_overlay_seconds "${builder_guest_dir}" || return 1
                rootfs_inject_outer_payload_atomic "${outer_image}" "${builder_guest_dir}" \
                    "${empty_overlay_dir}" "${protected_basename}" "${outer_reserve}" || return 1
                ;;
            alpine)
                _rootfs_builder_normalize_overlay_seconds "${builder_guest_dir}" || return 1
                if [[ "${ARCH}" == "aarch64" ]]; then
                    _rootfs_builder_normalize_overlay_seconds "${ivc_overlay_dir}" || return 1
                    rootfs_inject_outer_payload_atomic "${outer_image}" "${builder_guest_dir}" \
                        "${ivc_overlay_dir}" "${protected_basename}" "${outer_reserve}" || return 1
                else
                    rootfs_inject_outer_payload_atomic "${outer_image}" "${builder_guest_dir}" \
                        "${empty_overlay_dir}" "${protected_basename}" "${outer_reserve}" || return 1
                fi
                ;;
            debian)
                _rootfs_builder_normalize_overlay_seconds "${builder_guest_dir}" || return 1
                rootfs_inject_outer_payload_atomic "${outer_image}" "${builder_guest_dir}" \
                    "${empty_overlay_dir}" "${protected_basename}" "${outer_reserve}" || return 1
                ;;
            *)
                die "Unsupported rootfs builder: ${rootfs_builder} (supported: busybox, alpine, debian)"
                ;;
        esac
        success "Root filesystem injection completed: ${rootfs_builder}"
    done

    trap - EXIT
    rm -rf "${stage_dir}"
    [[ -z "${alpine_stage_dir}" ]] || rm -rf "${alpine_stage_dir}"
)

qemu_build_os_and_rootfs() {
    local action="$1"
    shift
    local os_steps=("$@")
    local rootfs_builder
    local action_log_dir
    action_log_dir="$(new_log_dir "platform" "qemu" "${action}-${ARCH}")"
    local summary_log="${action_log_dir}/summary.log"
    local parallel_steps=("${os_steps[@]}")

    for rootfs_builder in "${ROOTFS_BUILDERS[@]}"; do
        parallel_steps+=("qemu_rootfs_${rootfs_builder}_step")
    done

    if ! PARALLEL_LOG_DIR="${action_log_dir}" \
         PARALLEL_DEFER_COMPLETION=1 \
             run_parallel_functions "${action}-${ARCH}" "${parallel_steps[@]}" -- "${BUILD_ARGS[@]}"; then
        printf '[%s] COMPLETE %s-%s: parallel build failed\n' "$(date '+%F %T')" "${action}" "${ARCH}" | tee -a "${summary_log}"
        printf '[%s] Summary log: %s\n' "$(date '+%F %T')" "${summary_log}" | tee -a "${summary_log}"
        return 1
    fi

    qemu_rootfs_inject_platform_dir
    printf '[%s] COMPLETE %s-%s: all steps finished successfully\n' "$(date '+%F %T')" "${action}" "${ARCH}" | tee -a "${summary_log}"
    printf '[%s] Summary log: %s\n' "$(date '+%F %T')" "${summary_log}" | tee -a "${summary_log}"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    LOG_CREATE_DEFAULT_FILE="${LOG_CREATE_DEFAULT_FILE:-0}"
    source "${SCRIPT_DIR}/../lib/utils.sh"
    source "${SCRIPT_DIR}/../lib/rootfs.sh"
    source "${SCRIPT_DIR}/../lib/rootfs-compose.sh"
    cmd="${1:-}"
    shift 1 || true
    case "${cmd}" in
        ""|help|-h|--help)
            usage
            exit 0
            ;;
        aarch64|riscv64|x86_64|loongarch64)
            ARCH="$cmd"
            ROOTFS_ARCH="${ARCH}"
            PLATFORM_IMAGES_DIR="${ROOT_DIR}/IMAGES/qemu-${ARCH}"
            if [[ $# -eq 0 || "${1:-}" == "help" || "${1:-}" == "-h" || "${1:-}" == "--help" || "${1:-}" == --* ]]; then
                QEMU_ARCH="${ARCH}" usage
                exit 0
            fi
            OS="$1"
            shift 1 || true
            qemu_rootfs_parse_args "$@"
            if qemu_has_help_arg "${BUILD_ARGS[@]}"; then
                QEMU_ARCH="${ARCH}" usage
                exit 0
            fi
            case "${OS}" in
                linux)
                    qemu_build_os_and_rootfs "linux" linux
                    ;;
                arceos)
                    qemu_build_os_and_rootfs "arceos" arceos
                    ;;
                zephyr)
                    [[ "${ARCH}" == "aarch64" ]] || die "Zephyr guest build is currently only supported for qemu aarch64"
                    qemu_build_os_and_rootfs "zephyr" zephyr
                    ;;
                freertos)
                    [[ "${ARCH}" == "aarch64" ]] || die "FreeRTOS guest build is currently only supported for qemu aarch64"
                    qemu_build_os_and_rootfs "freertos" freertos
                    ;;
                all)
                    qemu_steps=(linux)
                    if [[ "${ARCH}" != "loongarch64" ]]; then
                        qemu_steps+=(arceos)
                    fi
                    if [[ "${ARCH}" == "aarch64" ]]; then
                        qemu_steps+=(zephyr freertos)
                    fi
                    qemu_build_os_and_rootfs "all" "${qemu_steps[@]}"
                    ;;
                clean)
                    qemu_steps=(linux)
                    if [[ "${ARCH}" != "loongarch64" ]]; then
                        qemu_steps+=(arceos)
                    fi
                    if [[ "${ARCH}" == "aarch64" ]]; then
                        qemu_steps+=(zephyr freertos)
                    fi
                    run_parallel_functions "clean-${ARCH}" "${qemu_steps[@]}" -- clean
                    qemu_rootfs_clean_outputs
                    ;;
                *)
                    die "Unknown os: ${OS} (supported: linux, arceos, zephyr, freertos, all)"
                    ;;
            esac
            ;;
        all)
            if [[ $# -eq 0 || "${1:-}" == "help" || "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
                QEMU_ARCH="all" usage
                exit 0
            fi

            if [[ "${1:-}" == --* ]]; then
                OS="all"
            else
                OS="$1"
                shift 1 || true
            fi

            for arch in aarch64 riscv64 x86_64 loongarch64; do
                "$0" "$arch" "${OS}" "$@" || { echo "[ERROR] $arch build failed" >&2; exit 1; }
            done
            ;;
        clean)
            for arch in aarch64 riscv64 x86_64 loongarch64; do
                "$0" "$arch" "clean" || { echo "[ERROR] $arch build failed" >&2; exit 1; }
            done
            ;;
        *)
        die "Unknown command: $cmd" >&2
        ;;
    esac
fi
